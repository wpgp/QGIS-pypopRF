    def reject(self):
        if self.is_busy:
            self._close_pending = True
            self.cancel_all()
            return
        super().reject()

    def closeEvent(self, event):
        if self.is_busy:
            self._close_pending = True
            self.cancel_all()
            event.ignore()
            return
        super().closeEvent(event)

    def _processing_completed(self):
        self._refresh_readiness()
        if self.is_busy:
            return
        self.mainProgressBar.hide()
        self.activity.finish()
        self.workCompleted.emit()
        if self._dispose_pending:
            self._dispose_resources()
            return
        if self._close_pending:
            self._close_pending = False
            self.reject()

    def dispose_when_idle(self):
        """Keep disposal owned by this Qt dialog after QGIS drops the plugin.

        QGIS unload removes the Python plugin instance immediately. A weak
        bound slot on that instance cannot own deferred worker cleanup.
        """
        self._dispose_pending = True
        self.runtime_presenter.close()
        self.settings_handler.close()
        self.hide()
        if self.is_busy:
            self.cancel_all()
        else:
            self._dispose_resources()

    def _dispose_resources(self):
        if self._disposed or self.is_busy:
            return
        self._disposed = True
        self.runtime_presenter.close()
        self.settings_handler.close()
        self.logger.close()
        self.activity.finish()
        self.deleteLater()

    @property
    def is_busy(self):
        return (self.process_executor.is_running or self.runtime_controller.is_running
                or self.import_controller.is_running or self.tools_controller.is_running)

    def cancel_all(self):
        self.process_executor.stop_analysis()
        self.runtime_controller.stop()
        self.import_controller.stop()
        self.tools_controller.stop()

