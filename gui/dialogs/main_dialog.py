    def _tools_busy_changed(self, busy):
        active = self._project_ready and not busy
        self.set_input_widgets_enabled(active)
        self.set_settings_widgets_enabled(active)
        for widget in (self.workingDirEdit, self.initProjectButton, self.setupRuntimeButton,
                       self.browsePythonButton, self.pythonPathEdit):
            widget.setEnabled(not busy)
        self.prepareInputsButton.setEnabled(not busy and bool(self.runtime_controller.python))
        self.summarizePopulationButton.setEnabled(False)
        if busy:
            self.mainStartButton.setText("Stop data tool")
            self.mainStartButton.setEnabled(True)
        else:
            self._refresh_readiness()
            self._result_selected()

