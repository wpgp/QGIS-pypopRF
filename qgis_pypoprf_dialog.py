    def _handle_file_change(self, file_type: str, path: str):
        """Handle file selection changes for input files.

        Args:
            file_type: Type of file being changed ('mastergrid', 'mask', etc.)
            path: New file path
        """

        if self._loading_project or not self.config_manager.config_path:
            return
        if self.is_busy:
            self._restore_file_widget(file_type)
            return
        if path:
            self._begin_import([path], file_type)
        else:
            self.config_manager.clear_config_value(file_type)
        self._refresh_readiness()

    def on_working_dir_changed(self, path: str):
        """Handle working directory change"""
        self.initProjectButton.setEnabled(bool(path))
        self._project_ready = False
        self.initProjectButton.setText("Open Project" if (Path(path) / "config.yaml").is_file()
                                       else "Create Project")
        # A candidate directory is not the active project until Create/Open.
        self.mainStartButton.setEnabled(False)
        self.set_input_widgets_enabled(False)
        self.set_settings_widgets_enabled(False)

    def init_project(self):
        """Initialize new pypopRF project.

        Creates project directory structure, initializes configuration,
        and enables UI elements for further setup.

        Raises:
            Exception: If project initialization fails
        """

        if self.is_busy:
            return
        self.console_handler.clear()
        self.mainProgressBar.setValue(0)

        working_dir = self.workingDirEdit.filePath()
        if not working_dir:
            self.logger.error("Please select working directory first")
            return

        try:
            self._project_ready = False
            self.set_input_widgets_enabled(False)
            self.set_settings_widgets_enabled(False)
            self.mainStartButton.setEnabled(False)
            # Create project structure and config
            existing = (Path(working_dir) / "config.yaml").is_file()
            if existing:
                self.config_manager.open_project(working_dir)
            else:
                self.config_manager.create_initial_config(working_dir)
            if self.config_manager.config_path:
                self.file_handler.set_working_dir(working_dir,
                    self.config_manager.get_config().get("data_dir", "data"))

                # Enable UI elements
                self.openProjectFolder.setEnabled(True)
                self.addToQgisCheckBox.setChecked(True)

                self._loading_project = True
                self._setup_cpu_cores_combo()
                self._load_project_inputs()

                # Load initial settings
                if not self.settings_handler.load_settings(self):
                    raise ValueError("Project settings could not be loaded")
                self._loading_project = False
                self._update_logging_settings(persist=False)
                self._project_ready = True
                self.set_input_widgets_enabled(True)
                self.set_settings_widgets_enabled(True)
                self.initProjectButton.setText("Open project")
                self.currentProjectLabel.setText(str(Path(self.config_manager.working_dir)))
                self.refresh_results()
                self._refresh_readiness()

                # Show next steps
                self.logger.info("Project initialized successfully!")
                self.logger.info("Select mastergrid, census and covariate files in Input Data.")
                self.logger.info("Review processing settings, then start the analysis.")

        except Exception as e:
            self.logger.error(f"Error initializing project: {str(e)}")
            self.set_input_widgets_enabled(False)
            self.set_settings_widgets_enabled(False)
            self.mainStartButton.setEnabled(False)
        finally:
            self._loading_project = False

    def add_covariate(self):
        """Add new covariate files to the project.

        Opens file dialog for selecting covariate files and adds them
        to the project data directory.
        """

        file_paths, _ = QtWidgets.QFileDialog.getOpenFileNames(
            self, "Select Covariate Files", "", "GeoTIFF files (*.tif *.tiff)"
        )
        paths, names = [], set()
        for path in file_paths:
            if self.covariate_handler.check_duplicate(path):
                self.logger.warning(f"Covariate already present: {path}")
                continue
            if Path(path).stem.casefold() in names:
                self.logger.warning(f"Duplicate covariate name: {path}")
                continue
            names.add(Path(path).stem.casefold())
            paths.append(path)
        if paths:
            self._begin_import(paths, "covariate")
        self._refresh_readiness()

    def open_project_folder(self):
        """Open project folder in system file explorer"""
        try:
            self.file_handler.open_folder(self.config_manager.working_dir)
        except Exception as exc:
            self.logger.error(str(exc))

    def _update_logging_settings(self, *args, persist=True):
        """Update logging configuration based on current UI state.

        Updates both config file and logger instance with new settings.
        """

        if self._loading_project or not self.config_manager.config_path:
            return
        try:
            validate_log_filename(self.logsColumnEdit.text())
        except ValueError as exc:
            self.logger.error(str(exc))
            return
        try:
            if persist:
                self.config_manager.update_config(
                    "logging",
                    {"level": self.comboBox.currentText(), "file": self.logsColumnEdit.text()},
                )
            self.console_handler.update_logging_settings(
                level=self.comboBox.currentText(), save_log=True,
                work_dir=self.config_manager.working_dir, filename=self.logsColumnEdit.text())
        except Exception as exc:
            self.logger.error(f"Could not configure diagnostics: {exc}")
            if not persist:
                raise

    def _handle_cpu_cores_changed(self, i_cores):
        """Handle changes to CPU core count setting.

        Args:
            i_cores: New CPU core count value
        """

        if self._loading_project or not self.config_manager.config_path:
            return
        if self.enableParallelCheckBox.isChecked():
            try:
                cores = int(i_cores) if i_cores else 0
                if cores > 0:
                    self.config_manager.update_config("max_workers", cores)
                    self.logger.debug(f"CPU cores set to {cores}")
            except Exception as exc:
                self.logger.warning(f"Could not apply the CPU core setting: {exc}")

    def _handle_block_size_changed(self, text):
        """Handle changes to processing block size.

        Args:
            text: New block size value in format "width, height"
        """

        if self._loading_project or not self.config_manager.config_path:
            return
        if self.enableBlockProcessingCheckBox.isChecked():
            try:
                w, h = map(int, text.replace(" ", "").split(","))
                if w > 0 and h > 0:
                    self.config_manager.update_config("block_size", [w, h])
            except Exception as exc:
                self.logger.warning(f"Could not apply the tile size: {exc}")

    def _handle_start_button(self):
        """Handle start/stop button click"""
        if self.tools_controller.is_running:
            self.tools_controller.stop()
            self.mainStartButton.setEnabled(False)
            self.mainStartButton.setText("Stopping data tool…")
        elif self.import_controller.is_running:
            self.import_controller.stop()
            self.mainStartButton.setEnabled(False)
            self.mainStartButton.setText("Stopping import…")
        elif not self.process_executor.is_running and not self.runtime_controller.is_running:
            self.process_executor.start_analysis()
        else:
            self.process_executor.stop_analysis()

    def _save_processing_settings(self, *args):
        if not self._loading_project and self.config_manager.config_path:
            self.settings_handler.save_settings(self)

    def _threshold_changed(self, *args):
        self.settings_handler._loaded_threshold = None
        self._save_processing_settings()

    def _load_project_inputs(self):
        config = self.config_manager.get_config()
        data = Path(self.config_manager.working_dir) / config.get("data_dir", "data")
        widgets = {"mastergrid": self.mastergridFileWidget, "mask": self.maskFileWidget,
                   "constrain": self.constrainFileWidget,
                   "census_data": self.populationCensusFileWidget,
                   "agesex_data": self.agesexCensusFileWidget}
        for key, widget in widgets.items():
            value = config.get(key)
            widget.setFilePath(str(data / value) if value else "")
        self.covariatesTable.setRowCount(0)
        for name, filename in config.get("covariates", {}).items():
            self.covariate_handler._add_covariate_row(filename, data, name=name, update=False)

    def _restore_file_widget(self, key):
        try:
            config = self.config_manager.get_config()
        except Exception as exc:
            self.logger.error(f"Could not read project settings: {exc}")
            self._project_ready = False
            config = {}
        data = Path(self.config_manager.working_dir) / config.get("data_dir", "data")
        widgets = {"mastergrid": self.mastergridFileWidget, "mask": self.maskFileWidget,
                   "constrain": self.constrainFileWidget,
                   "census_data": self.populationCensusFileWidget,
                   "agesex_data": self.agesexCensusFileWidget}
        widget = widgets[key]
        blocker = QSignalBlocker(widget)
        widget.setFilePath(str(data / config[key]) if config.get(key) else "")
        del blocker

    def reject(self):
        if self.is_busy:
            self._close_pending = True
            self.cancel_all()
            return
        super().reject()

    def closeEvent(self, event):
        if self.is_busy:
            self._close_pending = True
            self.cancel_all()
            event.ignore()
            return
        super().closeEvent(event)

    def _processing_completed(self):
        self._refresh_readiness()
        if self.is_busy:
            return
        self.workCompleted.emit()
        if self._close_pending:
            self._close_pending = False
            self.reject()

    @property
    def is_busy(self):
        return (self.process_executor.is_running or self.runtime_controller.is_running
                or self.import_controller.is_running or self.tools_controller.is_running)

    def cancel_all(self):
        self.process_executor.stop_analysis()
        self.runtime_controller.stop()
        self.import_controller.stop()
        self.tools_controller.stop()

    def _setup_visuals(self):
        metadata = configparser.ConfigParser()
        metadata.read(self.plugin_root / "metadata.txt", encoding="utf-8")
        self.setWindowTitle("pypopRF " + metadata.get("general", "version", fallback=""))
        for label in (self.currentProjectLabel, self.readinessLabel, self.runtimeStatusLabel,
                      self.resultSummaryLabel):
            label.setTextFormat(Qt.TextFormat.PlainText)
        for button, icon in ((self.initProjectButton, "/mActionFileNew.svg"),
                             (self.openProjectFolder, "/mActionFileOpen.svg"),
                             (self.addCovariateButton, "/mActionAddRasterLayer.svg"),
                             (self.refreshResultsButton, "/mActionRefresh.svg")):
            button.setIcon(QgsApplication.getThemeIcon(icon))
        self.mainStartButton.setDefault(True)
        self.mainStartButton.setMinimumWidth(130)
        self.mainStartButton.setShortcut(QKeySequence("Alt+R"))
        self.initProjectButton.setShortcut(QKeySequence("Alt+O"))
        self.addCovariateButton.setShortcut(QKeySequence("Alt+A"))
        self.mainStartButton.setToolTip("Run or stop the current analysis (Alt+R)")
        self.initProjectButton.setToolTip("Create or open the selected project folder (Alt+O)")
        self.selectionThresholdLimit.setToolTip(
            "Minimum normalized permutation importance. Higher values usually keep fewer predictors. "
            "A fallback retains usable predictors when none pass the threshold.")
        self.pythonPathEdit.setPlaceholderText("Python 3.12 executable")
        self.runtimeProgressBar.hide()
        self.cancelSetupButton.hide()
        self.openRunButton.setEnabled(False)
        self.addRunLayersButton.setEnabled(False)
        self.resultsTree.header().setSectionResizeMode(0, QtWidgets.QHeaderView.ResizeMode.Stretch)
        self.covariate_handler.on_changed = self._refresh_readiness

    def _runtime_changed(self, result):
        ready = bool(result["python"])
        self.runtimeStatusLabel.setText("Analysis engine ready" if ready else
                                       "Engine setup could not be completed. See Details." if result.get("error") else
                                       "Set up the analysis engine to begin")
        if result["candidates"] and not self.pythonPathEdit.text():
            self.pythonPathEdit.setText(result["candidates"][0])
        self.setupRuntimeButton.setText("Update / repair engine" if ready else "Set up engine")
        self.setupRuntimeButton.setEnabled(True)
        self.browsePythonButton.setEnabled(True)
        self.pythonPathEdit.setEnabled(True)
        self.runtimeProgressBar.hide()
        self.cancelSetupButton.hide()
        if result.get("error"):
            self.logger.error(result["error"])
        self._refresh_readiness()

    def _runtime_progress(self, value, message):
        self.runtimeProgressBar.setValue(value)
        self.runtimeStatusLabel.setText("Preparing the analysis engine…" if value < 30 else
                                       "Installing engine components…" if value < 85 else
                                       "Checking the analysis engine…" if value < 100 else
                                       "Analysis engine ready")
        self.logger.info(message)

    def _browse_python(self):
        path, _ = QtWidgets.QFileDialog.getOpenFileName(self, "Select Python 3.12 executable", "", "All files (*)")
        if path:
            self.pythonPathEdit.setText(path)

    def _setup_runtime(self):
        if self.is_busy:
            return
        python = self.pythonPathEdit.text().strip()
        if not python:
            self.runtimeStatusLabel.setText("Select a Python 3.12 executable first")
            return
        self.setupRuntimeButton.setEnabled(False)
        self.browsePythonButton.setEnabled(False)
        self.pythonPathEdit.setEnabled(False)
        self.runtimeProgressBar.show()
        self.cancelSetupButton.show()
        self.runtime_controller.setup(python)
        self._refresh_readiness()

    def _refresh_readiness(self):
        if self.process_executor.is_running or self.import_controller.is_running or self.tools_controller.is_running:
            return
        self.prepareInputsButton.setEnabled(bool(self.runtime_controller.python) and not self.is_busy)
        has_project = bool(self.config_manager.config_path)
        ready = False
        if has_project:
            try:
                config = self.config_manager.get_config()
            except Exception as exc:
                self._project_ready = False
                self.mainStartButton.setEnabled(False)
                self.set_input_widgets_enabled(False)
                self.set_settings_widgets_enabled(False)
                self.readinessLabel.setText("Project settings cannot be read. Reopen the project.")
                self.logger.error(str(exc))
                return
            ready = bool(config.get("mastergrid") and config.get("census_data") and config.get("covariates"))
        active = (self._project_ready and has_project
                  and Path(self.workingDirEdit.filePath()).resolve() == Path(self.config_manager.working_dir).resolve())
        engine = bool(self.runtime_controller.python)
        self.mainStartButton.setEnabled(ready and active and engine and not self.is_busy)
        self.mainStartButton.setText("Run analysis")
        self.readinessLabel.setText(
            "Ready to run your population analysis." if ready and active and engine else
            "Set up the analysis engine." if not engine else
            "Create or open a project." if not active else
            "Add a zone grid, population census and at least one covariate.")

    def _begin_import(self, paths, kind):
        if self.is_busy or not self._project_ready:
            return
        config = self.config_manager.get_config()
        self.set_input_widgets_enabled(False)
        self.set_settings_widgets_enabled(False)
        self.workingDirEdit.setEnabled(False)
        self.initProjectButton.setEnabled(False)
        self.setupRuntimeButton.setEnabled(False)
        self.mainStartButton.setEnabled(True)
        self.mainStartButton.setText("Cancel import")
        self.mainProgressBar.setValue(0)
        self.import_controller.start(self.config_manager.working_dir,
            config.get("data_dir", "data"), paths, kind, self.logger)

    def _import_progress(self, percent, name):
        self.mainProgressBar.setValue(percent)
        self.mainProgressBar.setFormat(f"Importing {name}…")

    def _imports_finished(self, result):
        kind = result["kind"]
        try:
            if kind == "covariate":
                self.covariate_handler.add_covariates(result["filenames"])
            else:
                if result["filenames"]:
                    self.config_manager.update_config(kind, result["filenames"][-1])
                self._restore_file_widget(kind)
            for error in result["errors"]:
                self.logger.error(error)
        except Exception as exc:
            self.logger.error(f"Could not register imported files: {exc}")
            if kind != "covariate":
                self._restore_file_widget(kind)
        self.set_input_widgets_enabled(True)
        self.set_settings_widgets_enabled(True)
        self.workingDirEdit.setEnabled(True)
        self.initProjectButton.setEnabled(True)
        self.setupRuntimeButton.setEnabled(True)
        self.mainProgressBar.setFormat("Import completed" if not result["errors"] else "Import could not be completed; see Details")
        self._refresh_readiness()

    def refresh_results(self):
        self.resultsTree.clear()
        self._result_selected()
        if not self.config_manager.config_path:
            return
        try:
            config = self.config_manager.get_config()
            root = (Path(self.config_manager.working_dir) / config.get("output_dir", "output") / "runs").resolve()
        except Exception as exc:
            self.resultSummaryLabel.setText("Project settings could not be read. See Details.")
            self.logger.error(str(exc))
            return
        if not root.is_dir():
            self.resultSummaryLabel.setText("No analyses yet. Add input data and run your first analysis.")
            return
        complete = 0
        try:
            directories = sorted(root.iterdir(), reverse=True)[:200]
        except OSError as exc:
            self.logger.error(f"Could not read result history: {exc}")
            return
        for directory in directories:
            if not directory.is_dir() or directory.is_symlink():
                continue
            path = directory / "manifest.json"
            try:
                manifest = read_manifest(path)
                status = manifest["status"]
                outputs = population_paths(directory, manifest)
                item = QtWidgets.QTreeWidgetItem([directory.name, status.capitalize(), str(len(outputs))])
                item.setData(0, Qt.ItemDataRole.UserRole, str(directory))
                self.resultsTree.addTopLevelItem(item)
                complete += status == "complete"
            except (OSError, ValueError, TypeError):
                continue
        self.resultSummaryLabel.setText(f"{complete} completed analyses. Select a run to view its results.")
        self._result_selected()

    def _selected_run(self):
        selected = self.resultsTree.selectedItems()
        return Path(selected[0].data(0, Qt.ItemDataRole.UserRole)) if selected else None

    def _result_selected(self):
        selected = self.resultsTree.selectedItems()
        self.openRunButton.setEnabled(bool(selected))
        complete = False
        if selected:
            root = self._selected_run()
            try:
                manifest = read_manifest(root / "manifest.json")
                complete = bool(population_paths(root, manifest))
            except (OSError, ValueError, TypeError):
                pass
        self.addRunLayersButton.setEnabled(complete and self.iface is not None)
        self.summarizePopulationButton.setEnabled(complete and bool(self.runtime_controller.python) and not self.is_busy)
        try:
            self.quality_panel.load_run(self._selected_run())
        except Exception as exc:
            self.logger.warning(f"Could not display quality diagnostics: {exc}")

    def _open_selected_run(self):
        path = self._selected_run()
        if path:
            try:
                self.file_handler.open_folder(str(path))
            except Exception as exc:
                self.logger.error(str(exc))

    def _add_selected_run(self):
        root = self._selected_run()
        if root is None or self.iface is None:
            return
        try:
            manifest = read_manifest(root / "manifest.json")
            self.layer_integration.iface = self.iface
            self.layer_integration.add_run(root, population_paths(root, manifest))
        except (OSError, ValueError, TypeError) as exc:
            self.logger.error(f"Could not load this run: {exc}")

    def _setup_feature_widgets(self):
        actions = QtWidgets.QHBoxLayout()
        self.prepareInputsButton = QtWidgets.QPushButton("Prepare / align inputs…")
        self.useLayerButton = QtWidgets.QPushButton("Use a QGIS layer…")
        self.prepareInputsButton.setToolTip("Check source data and create a separate, aligned project without changing the originals")
        actions.addWidget(self.prepareInputsButton)
        actions.addWidget(self.useLayerButton)
        actions.addStretch()
        self.inputLayout.insertLayout(0, actions)
        self.prepareInputsButton.clicked.connect(self._open_preparation)
        self.useLayerButton.clicked.connect(self._use_project_layer)
        self.summarizePopulationButton = QtWidgets.QPushButton("Population in an area…")
        self.resultActions.addWidget(self.summarizePopulationButton)
        self.summarizePopulationButton.setEnabled(False)
        self.summarizePopulationButton.clicked.connect(self._open_population_summary)
        self.quality_panel = QualityPanel(self)
        self.quality_panel.showZonesRequested.connect(self._show_quality_zones)
        quality_scroll = QtWidgets.QScrollArea()
        quality_scroll.setWidgetResizable(True)
        quality_scroll.setWidget(self.quality_panel)
        splitter = QtWidgets.QSplitter(Qt.Orientation.Vertical)
        self.resultsLayout.removeWidget(self.resultsTree)
        self.resultsTree.setMinimumHeight(110)
        splitter.addWidget(self.resultsTree)
        splitter.addWidget(quality_scroll)
        splitter.setStretchFactor(0, 1)
        splitter.setStretchFactor(1, 3)
        self.resultsLayout.insertWidget(1, splitter, 1)
        self.quality_panel.load_run(None)

    def _tools_busy_changed(self, busy):
        active = self._project_ready and not busy
        self.set_input_widgets_enabled(active)
        self.set_settings_widgets_enabled(active)
        for widget in (self.workingDirEdit, self.initProjectButton, self.setupRuntimeButton,
                       self.browsePythonButton, self.pythonPathEdit):
            widget.setEnabled(not busy)
        self.prepareInputsButton.setEnabled(not busy and bool(self.runtime_controller.python))
        self.summarizePopulationButton.setEnabled(False)
        if busy:
            self.mainStartButton.setText("Stop data tool")
            self.mainStartButton.setEnabled(True)
        else:
            self._refresh_readiness()
            self._result_selected()

    def _tools_progress(self, percent, message):
        self.mainProgressBar.setValue(percent)
        self.mainProgressBar.setFormat(message)
        self.logger.info(message)

    def _open_preparation(self):
        if self.is_busy or not self.runtime_controller.python:
            return
        try:
            if self._preparation_window is None:
                wizard = PreparationWizard(self)
                self._preparation_window = wizard
                wizard.prepared.connect(self._open_prepared_project)
                wizard.finished.connect(lambda: self._close_feature_window("_preparation_window"))
            self._preparation_window.show()
            self._preparation_window.raise_()
        except Exception as exc:
            self.logger.error(f"Could not open the preparation wizard: {exc}")

    def _close_feature_window(self, attribute):
        window = getattr(self, attribute)
        setattr(self, attribute, None)
        if window:
            window.deleteLater()

    def _open_prepared_project(self, root):
        if self.is_busy:
            return
        try:
            # Validate without switching active paths before the explicit open.
            manager = ConfigManager(self.logger)
            manager.open_project(root)
            self.workingDirEdit.setFilePath(str(root))
            self.init_project()
        except Exception as exc:
            self.logger.error(f"Could not open the prepared project: {exc}")

    def _use_project_layer(self):
        if self.is_busy or not self._project_ready:
            return
        roles = {"Zone ID grid": "mastergrid", "Predictor": "covariate",
                 "Excluded-area mask": "mask", "Allowed-area constraint": "constrain"}
        label, accepted = QtWidgets.QInputDialog.getItem(self, "Import a QGIS layer", "Use as", list(roles), 0, False)
        if not accepted:
            return
        try:
            record = choose_project_layer(self, "raster")
            if record:
                if Path(record["path"]).suffix.lower() not in {".tif", ".tiff"}:
                    raise ValueError("Export this input as a GeoTIFF first, or use the preparation wizard")
                self._begin_import([record["path"]], roles[label])
        except (ValueError, OSError) as exc:
            self.logger.warning(str(exc))

    def _show_quality_zones(self, payload):
        try:
            self.layer_integration.show_zone_centroids(payload)
        except Exception as exc:
            self.logger.warning(f"Could not map diagnostic centroids: {exc}")

    def _open_population_summary(self):
        if self.is_busy or not self.runtime_controller.python:
            return
        try:
            root = self._selected_run()
            if not root:
                return
            manifest = read_manifest(root / "manifest.json")
            maps = population_paths(root, manifest)
            if not maps:
                return
            if self._summary_window is None:
                inventory = manifest.get("artifacts", [])
                hashes = {}
                if isinstance(inventory, list):
                    for artifact in inventory:
                        if isinstance(artifact, dict) and isinstance(artifact.get("path"), str):
                            candidate = root / artifact["path"]
                            if candidate in maps:
                                hashes[str(candidate)] = artifact.get("sha256")
                window = PopulationSummaryDialog(self, maps, hashes)
                self._summary_window = window
                window.finished.connect(lambda: self._close_feature_window("_summary_window"))
            self._summary_window.show()
            self._summary_window.raise_()
        except Exception as exc:
            self.logger.warning(f"Could not open the population summary: {exc}")
